"""Analyze completed world-model and simulator runs without inventing outcomes.

Only completed summaries and saved predictions are read. Bootstrap units are
whole test episodes, jointly sampled across fixed model seeds. Controller
comparisons require matching environment seed, domain, parameters and protocol.
No synthetic fixtures are generated by this analysis.
"""
import argparse
import csv
import json
from pathlib import Path
import re
import math
import numpy as np


def read_json(path, warnings):
    try:
        return json.loads(Path(path).read_text(encoding='utf-8-sig'))
    except (OSError, ValueError) as error:
        warnings.append(f'Cannot read completed JSON {path}: {error}')
        return None


def clean_json(value):
    if isinstance(value, dict):
        return {str(k): clean_json(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [clean_json(v) for v in value]
    if isinstance(value, np.ndarray):
        return clean_json(value.tolist())
    if isinstance(value, (np.floating, float)):
        return float(value) if np.isfinite(value) else None
    if isinstance(value, np.integer):
        return int(value)
    return value


def save_json(path, value):
    path.write_text(json.dumps(clean_json(value), ensure_ascii=False, indent=2,
                               allow_nan=False), encoding='utf-8')


def write_csv(path, rows):
    if not rows:
        return
    fields = list(dict.fromkeys(k for row in rows for k in row))
    with path.open('w', newline='', encoding='utf-8-sig') as stream:
        writer = csv.DictWriter(stream, fieldnames=fields)
        writer.writeheader()
        writer.writerows([{k: json.dumps(v, ensure_ascii=False) if isinstance(v, (list, dict)) else v
                          for k, v in clean_json(row).items()} for row in rows])


def wilson(successes, total, z=1.959963984540054):
    if total == 0:
        return None, None
    p = successes/total
    denominator = 1+z*z/total
    center = (p+z*z/(2*total))/denominator
    radius = z*math.sqrt(p*(1-p)/total+z*z/(4*total*total))/denominator
    return max(0., center-radius), min(1., center+radius)


def bootstrap_mean(values, repeats, rng):
    values = np.asarray(values, dtype=float)
    if len(values) == 0:
        return None, None, None
    mean = values.mean(0)
    if len(values) < 2:
        return mean, None, None
    sampled = values[rng.integers(0, len(values), (repeats, len(values)))].mean(1)
    return mean, np.quantile(sampled, .025, axis=0), np.quantile(sampled, .975, axis=0)


def grouped_forecast_statistics(records, repeats, rng):
    """records: model seeds; each has episode_id -> (sum_error[H], count[H]).

    Resampling the same episode IDs for every fixed model seed avoids treating
    training seeds, overlapping windows or force coordinates as independent data.
    """
    if not records:
        return None
    common = sorted(set.intersection(*(set(r) for r in records)))
    if not common:
        return None
    sums = np.stack([[r[e][0] for e in common] for r in records])
    counts = np.stack([[r[e][1] for e in common] for r in records])
    by_seed = sums.sum(1)/counts.sum(1)
    mean = by_seed.mean(0)
    if len(common) >= 2:
        draws = rng.integers(0, len(common), (repeats, len(common)))
        values = np.stack([(sums[:, draw].sum(1)/counts[:, draw].sum(1)).mean(0) for draw in draws])
        low, high = np.quantile(values, [.025, .975], axis=0)
    else:
        low = high = None
    return {'mean': mean, 'ci_low': low, 'ci_high': high,
            'seed_sd': by_seed.std(0, ddof=1) if len(records)>1 else None,
            'episodes': len(common), 'model_seeds': len(records),
            'common_episode_ids': common,
            'ci_scope': 'whole test episodes, common draws across fixed training seeds'}


def episode_errors(prediction, target, ids, mapping):
    error = np.abs(prediction-target)
    if error.ndim == 2:
        error = error[..., None]
    result = {}
    for index in np.unique(ids):
        selected = error[ids == index]
        name = mapping.get(int(index))
        if name is None:
            continue
        result[name] = (selected.sum((0,2)), np.full(selected.shape[1],
                                                     selected.shape[0]*selected.shape[2], dtype=float))
    return result


def world_results(directory, repeats, rng, warnings):
    directory = Path(directory)
    manifest = read_json(directory/'data_manifest.json', warnings) if (directory/'data_manifest.json').exists() else None
    summaries = {}
    if (directory/'all_runs.json').exists():
        all_runs = read_json(directory/'all_runs.json', warnings)
        for row in all_runs or []:
            if 'variant' in row and 'seed' in row:
                summaries[f'{row["variant"]}_seed{row["seed"]}'] = row
    for path in directory.glob('*/summary.json'):
        row = read_json(path, warnings)
        if row and 'variant' in row and 'seed' in row:
            summaries[path.parent.name] = row
    accumulators, calibration_rows, individual = {}, [], []
    for name, summary in summaries.items():
        variant, seed = summary['variant'], summary['seed']
        for split, methods in summary.get('evaluation', {}).items():
            if not split.startswith('test'):
                continue
            for method, metrics in methods.items():
                if isinstance(metrics, dict):
                    individual.append({'run':name,'variant':variant,'seed':seed,'split':split,
                                       'method':method, **metrics})
            path = directory/name/f'predictions_{split}.npz'
            if not path.exists():
                warnings.append(f'Missing saved predictions: {path}; summary-only metrics retained, no bootstrap fabricated.')
                continue
            with np.load(path, allow_pickle=False) as opened:
                data = {k:opened[k] for k in opened.files}
            if 'episode_index' not in data:
                warnings.append(f'{path} has no episode grouping; no frame bootstrap substituted.')
                continue
            if isinstance(manifest, list):
                mapping = {i:r['episode_id'] for i,r in enumerate(x for x in manifest if x.get('split')==split)}
            else:
                # Never assume numeric indexes from different runs identify the same episode.
                mapping = {int(i):f'{name}:episode_{int(i)}' for i in np.unique(data['episode_index'])}
                warnings.append(f'{path}: no shared manifest; cross-model-seed bootstrap cannot align episode IDs.')
            for metric in ('tactile','peak','height'):
                if 'pred_'+metric not in data or 'true_'+metric not in data:
                    continue
                records = episode_errors(data['pred_'+metric],data['true_'+metric],data['episode_index'],mapping)
                accumulators.setdefault((variant,split,metric), {})[seed] = records
            calibration = summary.get('calibration', {})
            if not calibration and (directory/name/'calibration.json').exists():
                calibration = read_json(directory/name/'calibration.json',warnings) or {}
            pq, hq = calibration.get('peak_radius_N'), calibration.get('height_radius_m')
            if pq is not None and hq is not None and all(k in data for k in ('true_peak','pred_peak','true_height','pred_height')):
                good_peak = (data['true_peak'] <= data['pred_peak']+pq).all((1,2))
                good_height = (np.abs(data['true_height']-data['pred_height']) <= hq).all((1,2))
                covered = [bool((good_peak[data['episode_index']==i] & good_height[data['episode_index']==i]).all())
                           for i in np.unique(data['episode_index'])]
                low,high = wilson(sum(covered),len(covered))
                calibration_rows.append({'run':name,'variant':variant,'seed':seed,'split':split,
                    'covered_episodes':sum(covered),'episodes':len(covered),'joint_episode_coverage':np.mean(covered),
                    'wilson_low':low,'wilson_high':high,'peak_radius_N':pq,'height_radius_m':hq,
                    'calibration_episodes':calibration.get('calibration_episodes'),
                    'nominal_coverage':1-calibration.get('alpha_joint',.1),
                    'scope':'empirical OOD stress test; exchangeable guarantee not inherited' if 'ood' in split else
                            'empirical held-out recording distribution; not deployed policy coverage'})
    grouped = []
    for (variant,split,metric),records in accumulators.items():
        stats = grouped_forecast_statistics(list(records.values()),repeats,rng)
        if stats:
            grouped.append({'variant':variant,'split':split,'metric':metric,**stats})
        else:
            warnings.append(f'No shared test episode IDs across seeds for {variant}/{split}/{metric}.')
    paired=[]
    for (variant,split,metric),touch_records in accumulators.items():
        if variant != 'visuotactile' or ('vision',split,metric) not in accumulators:
            continue
        vision_records=accumulators[('vision',split,metric)]
        differences=[]
        for seed in sorted(set(touch_records)&set(vision_records)):
            touch,vision=touch_records[seed],vision_records[seed]
            matched={}
            for episode in set(touch)&set(vision):
                if np.array_equal(touch[episode][1],vision[episode][1]):
                    matched[episode]=(touch[episode][0]-vision[episode][0],touch[episode][1])
                else:
                    warnings.append(f'Unequal forecast counts at {episode}/{split}/{seed}; paired modality comparison excludes this episode.')
            if matched:differences.append(matched)
        stats=grouped_forecast_statistics(differences,repeats,rng)
        if stats:paired.append({'comparison':'visuotactile minus vision','split':split,'metric':metric,**stats})
    return {'completed_runs':len(summaries),'runs':summaries,'individual':individual,
            'grouped_forecasts':grouped,'paired_modality_differences':paired,'calibration':calibration_rows}


def protocol_key(summary,cohort):
    return (summary.get('takeover'), summary.get('intervention_end'), summary.get('source_sha256'),
            tuple(summary.get('control_dimensions',[])),
            tuple(summary.get('zero_dimensions_during_intervention',[])),cohort)


def event_metrics(rows):
    fields = ['sustained_native_success','sustained_success_within_force_budget',
              'any_native_success','final_native_success','force_budget_exceeded',
              'setup_force_budget_exceeded','bilateral_contact_at_takeover',
              'intervention_force_budget_exceeded']
    # Accept the explicit strict-height names supplied by the evaluator. Do not
    # infer a stricter success event from max height or native task success.
    fields += sorted({key for row in rows for key,value in row.items()
                      if isinstance(value,bool) and ('strict' in key or '10cm' in key)})
    return list(dict.fromkeys(fields))


def policy_identity(name):
    """Parse original and reward-ablation policy names without merging cohorts."""
    tokens=name.split('_')
    if not tokens or tokens[0] not in ('vision','visuotactile'):
        return None
    seeds=[int(t[4:]) for t in tokens if re.fullmatch(r'seed\d+',t)]
    kinds=[t for t in tokens if t in ('bc','rl')]
    rewards=[t for t in tokens if t in ('native','height')]
    if len(seeds)!=1 or len(kinds)!=1 or len(rewards)>1:
        return None
    reward=rewards[0] if rewards else None
    margin='margin' in tokens
    method=tokens[0]+('_margin' if margin else '')+('_'+reward if reward else '')+'_'+kinds[0]
    return {'variant':tokens[0],'seed':seeds[0],'kind':kinds[0],
            'reward':reward,'margin':margin,'method':method}


def grouped_control_results(runs,repeats,rng,warnings):
    """Fixed trained policies, common environment draws, fixed ID/OOD mixture.

    A policy seed does not create another independent environment observation.
    Singleton scripted baselines retain one policy and the same episode units.
    """
    methods={}
    for run in runs:
        if run['status']!='primary':
            continue
        identity=policy_identity(run['name'])
        if identity:
            name=identity['method']
        elif run['summary'].get('controller') in ('script','force_feedback'):
            name=run['summary']['controller']
        else:
            continue
        methods.setdefault(name,[]).append(run)
    metrics=('sustained_10cm_lift_within_force_budget','sustained_10cm_lift_success',
             'force_budget_exceeded','intervention_force_budget_exceeded','full_episode_peak_normal_N','native_shaped_return')
    results=[];records={}
    for name,group in methods.items():
        if len({r['protocol'] for r in group})!=1:
            warnings.append(f'Mixed protocols within {name}; no pooled method summary.')
            continue
        indexed=[{(r['seed'],r['domain']):r for r in run['rows']} for run in group]
        common=sorted(set.intersection(*(set(r) for r in indexed)))
        common=[key for key in common if all(r[key].get('params')==indexed[0][key].get('params') for r in indexed)
                and indexed[0][key].get('params') is not None]
        for domain in ('all','id','ood'):
            keys=[key for key in common if domain=='all' or key[1]==domain]
            if not keys:
                continue
            # Keep the designed domain proportions fixed while resampling whole
            # episodes inside each domain; every policy uses the same draws.
            strata=[np.array([i for i,k in enumerate(keys) if k[1]==d]) for d in sorted({k[1] for k in keys})]
            draws=np.concatenate([indices[rng.integers(0,len(indices),(repeats,len(indices)))] for indices in strata],axis=1)
            for metric in metrics:
                if not all(metric in row[key] for row in indexed for key in keys):
                    continue
                values=np.array([[float(row[key][metric]) for key in keys] for row in indexed])
                per_policy=values.mean(1)
                per_episode=values.mean(0)
                estimate=per_episode.mean()
                boot=per_episode[draws].mean(1)
                lo,hi=np.quantile(boot,[.025,.975])
                results.append({'method':name,'domain':domain,'metric':metric,'estimate':estimate,
                    'ci_low':lo,'ci_high':hi,'policy_runs':len(group),'environment_episodes':len(keys),
                    'training_seed_sd':per_policy.std(ddof=1) if len(group)>1 else None,
                    'per_policy_counts':values.sum(1).tolist() if metric not in ('full_episode_peak_normal_N','native_shaped_return') else None,
                    'per_policy_estimates':per_policy,'run_names':[r['name'] for r in group],
                    'ci_method':'stratified whole-environment bootstrap; shared draws across fixed trained policies; ID/OOD counts fixed'})
                records[(name,domain,metric)]={'keys':keys,'values':per_episode,'protocol':group[0]['protocol'],
                    'params':{key:indexed[0][key]['params'] for key in keys},'policies':len(group)}
    paired=[]
    for (name,domain,metric),record in records.items():
        baselines=['script','force_feedback']
        if name.endswith('_rl'):
            baselines.append(name.split('_')[0]+'_bc')
        if name.startswith('visuotactile_'):
            baselines.append(name.replace('visuotactile_','vision_',1))
        if '_margin_' in name:
            baselines.append(name.replace('_margin_','_',1))
        if '_height_' in name:
            baselines.append(name.replace('_height_','_native_',1))
        for baseline in dict.fromkeys(baselines):
            other=records.get((baseline,domain,metric))
            if baseline==name or other is None or record['protocol']!=other['protocol']:
                continue
            aa=dict(zip(record['keys'],record['values']));bb=dict(zip(other['keys'],other['values']))
            keys=sorted(k for k in set(aa)&set(bb) if record['params'][k]==other['params'][k])
            if not keys:
                continue
            delta=np.array([aa[k]-bb[k] for k in keys])
            strata=[np.array([i for i,k in enumerate(keys) if k[1]==d]) for d in sorted({k[1] for k in keys})]
            draws=np.concatenate([indices[rng.integers(0,len(indices),(repeats,len(indices)))] for indices in strata],axis=1)
            lo,hi=np.quantile(delta[draws].mean(1),[.025,.975])
            paired.append({'method':name,'baseline':baseline,'domain':domain,'metric':metric,
                'run_minus_baseline':delta.mean(),'ci_low':lo,'ci_high':hi,'paired_environments':len(keys),
                'fixed_policies':record['policies'],'baseline_fixed_policies':other['policies'],
                'ci_method':'stratified paired environment bootstrap of fixed-policy averages'})
    return results,paired


def controls_results(directory, repeats, rng, primary_takeover, warnings):
    runs = []
    for path in sorted(Path(directory).glob('**/summary.json')):
        summary = read_json(path,warnings)
        if not summary or 'controller' not in summary or 'metrics' not in summary:
            continue
        rowpath = path.parent/'episodes.jsonl'
        if not rowpath.exists():
            warnings.append(f'{path}: per-episode records absent; no paired/bootstrap result inferred from averages.')
            continue
        try:
            rows = [json.loads(line) for line in rowpath.read_text(encoding='utf-8-sig').splitlines() if line.strip()]
        except (OSError,ValueError) as error:
            warnings.append(f'{rowpath}: {error}')
            continue
        pairs = [(r.get('seed'),r.get('domain')) for r in rows]
        if len(set(pairs)) != len(pairs):
            warnings.append(f'{rowpath}: duplicate seed/domain; run excluded rather than double-counted.')
            continue
        expected = summary.get('metrics',{}).get('all',{}).get('n')
        if expected is not None and len(rows) != expected:
            warnings.append(f'{rowpath}: {len(rows)} rows but summary n={expected}; run excluded.')
            continue
        for row in rows:
            if 'intervention_peak_normal_N' in row and 'force_budget' in row:
                row['intervention_force_budget_exceeded'] = row['intervention_peak_normal_N'] > row['force_budget']
        final_protocol=(summary.get('takeover')==primary_takeover
                        and summary.get('control_dimensions')==[2,6]
                        and summary.get('zero_dimensions_during_intervention')==[0,1,3,4,5])
        cohort=path.parent.parent.name
        runs.append({'name':path.parent.name,'path':str(path.parent.resolve()),'summary':summary,'cohort':cohort,
                     'protocol':protocol_key(summary,cohort),'rows':rows,
                     'status':'primary' if final_protocol else 'diagnostic_other_protocol'})
    primary_cohorts={r['cohort'] for r in runs if r['status']=='primary'}
    if len(primary_cohorts)>1:
        raise ValueError('Different evaluation cohorts cannot share a report or algorithm bootstrap. '
                         'Pass --controls with one specific cohort directory: '+', '.join(sorted(primary_cohorts)))
    if primary_cohorts=={'evaluation_goal_aligned'}:
        expected_seeds=set(range(20291000,20291020))
        for run in runs:
            if run['status']=='primary' and {r['seed'] for r in run['rows']}!=expected_seeds:
                raise ValueError(f'{run["name"]} does not contain exactly the 20 fresh reward-ablation environment seeds; '
                                 'do not substitute the original pilot or partial runs.')
    statistics = []
    for run in runs:
        for domain in ['all','id','ood']:
            rows = [r for r in run['rows'] if domain=='all' or r.get('domain')==domain]
            if not rows:
                continue
            for field in event_metrics(rows):
                if not all(field in r for r in rows):
                    continue
                k,n = sum(bool(r[field]) for r in rows),len(rows)
                low,high = wilson(k,n)
                statistics.append({'run':run['name'],'status':run['status'],'takeover':run['protocol'][0],
                    'domain':domain,'metric':field,'kind':'binary','count':k,'n':n,'estimate':k/n,
                    'ci_low':low,'ci_high':high,'ci_method':'Wilson 95%, environment-seed episodes'})
            for field in ('full_episode_peak_normal_N','setup_peak_normal_N','intervention_peak_normal_N',
                          'max_relative_height_m','native_shaped_return'):
                if not all(field in r for r in rows):
                    continue
                values = [r[field] for r in rows]
                mean,low,high = bootstrap_mean(values,repeats,rng)
                statistics.append({'run':run['name'],'status':run['status'],'takeover':run['protocol'][0],
                    'domain':domain,'metric':field,'kind':'continuous','n':len(rows),'estimate':mean,
                    'ci_low':low,'ci_high':high,'ci_method':'whole-environment-seed bootstrap 95%'})
            if all('setup_force_budget_exceeded' in r for r in rows):
                clean = [r for r in rows if not r['setup_force_budget_exceeded']]
                if clean and all('sustained_native_success' in r for r in clean):
                    k,n=sum(bool(r['sustained_native_success']) for r in clean),len(clean)
                    low,high=wilson(k,n)
                    statistics.append({'run':run['name'],'status':run['status'],'takeover':run['protocol'][0],
                        'domain':domain,'metric':'native_success_given_setup_within_budget','kind':'conditional_binary',
                        'count':k,'n':n,'all_episode_n':len(rows),'estimate':k/n,'ci_low':low,'ci_high':high,
                        'ci_method':'Wilson 95%; explicitly conditioned, not overall success'})
    paired = []
    candidate_pairs = set()
    for i,run in enumerate(runs):
        for j,baseline in enumerate(runs):
            if i==j or run['protocol'] != baseline['protocol']:
                continue
            base_type = baseline['summary'].get('controller')
            if base_type in ('script','force_feedback') and run['summary'].get('controller') != base_type:
                candidate_pairs.add((i,j))
            else:
                identity=policy_identity(run['name']);other=policy_identity(baseline['name'])
                if identity and other and identity['seed']==other['seed']:
                    same_variant=identity['variant']==other['variant']
                    same_reward=identity['reward']==other['reward']
                    same_margin=identity['margin']==other['margin']
                    same_kind=identity['kind']==other['kind']
                    if ((same_variant and identity['kind']=='rl' and other['kind']=='bc')
                        or (same_variant and same_kind and same_margin and identity['reward']=='height' and other['reward']=='native')
                        or (same_variant and same_kind and same_reward and identity['margin'] and not other['margin'])
                        or (same_kind and same_reward and same_margin and identity['variant']=='visuotactile' and other['variant']=='vision')):
                        candidate_pairs.add((i,j))
    for i,j in sorted(candidate_pairs):
        run,base=runs[i],runs[j]
        aa={(r['seed'],r.get('domain')):r for r in run['rows']}
        bb={(r['seed'],r.get('domain')):r for r in base['rows']}
        common = sorted(set(aa)&set(bb))
        valid=[]
        for key in common:
            if 'params' not in aa[key] or 'params' not in bb[key] or aa[key]['params'] != bb[key]['params']:
                warnings.append(f'Unmatched/unknown physical parameters at {key}, {run["name"]} vs {base["name"]}; pair excluded.')
            else:
                valid.append(key)
        fields=set(event_metrics(run['rows']))&set(event_metrics(base['rows']))
        fields.update(('full_episode_peak_normal_N','setup_peak_normal_N','intervention_peak_normal_N','native_shaped_return'))
        for domain in ['all','id','ood']:
            keys=[k for k in valid if domain=='all' or k[1]==domain]
            if not keys:
                continue
            for field in sorted(fields):
                if not all(field in aa[k] and field in bb[k] for k in keys):
                    continue
                delta=np.array([float(aa[k][field])-float(bb[k][field]) for k in keys])
                mean,low,high=bootstrap_mean(delta,repeats,rng)
                paired.append({'run':run['name'],'baseline':base['name'],'status':run['status'],
                    'takeover':run['protocol'][0],'domain':domain,'metric':field,'paired_n':len(keys),
                    'run_minus_baseline':mean,'ci_low':low,'ci_high':high,
                    'ci_method':'paired environment-seed bootstrap 95%, identical recorded physical parameters',
                    'higher':int((delta>0).sum()),'ties':int((delta==0).sum()),'lower':int((delta<0).sum()),
                    'positive_is_better':field in ('sustained_native_success','sustained_success_within_force_budget','native_shaped_return')
                                         or ('success' in field) or field.startswith('sustained_10cm_lift')})
    grouped,grouped_paired=grouped_control_results(runs,repeats,rng,warnings)
    audits=[]
    for parent in sorted({str(Path(r['path']).parent) for r in runs if r['status']=='primary'}):
        path=Path(parent)/'pairing_audit.json'
        if path.exists():
            audit=read_json(path,warnings)
            if audit:
                audits.append({'path':str(path.resolve()),**audit})
    return {'completed_runs':len(runs),'runs':runs,'statistics':statistics,'paired':paired,
            'grouped_methods':grouped,'grouped_paired':grouped_paired,'primary_takeover':primary_takeover,
            'pairing_audits':audits}


def executed_forecast_results(directory,warnings):
    directory=Path(directory)
    if not (directory/'metrics.csv').exists():
        return {'rows':[],'grouped':[],'provenance':None}
    provenance=read_json(directory/'provenance.json',warnings) if (directory/'provenance.json').exists() else None
    with (directory/'metrics.csv').open(encoding='utf-8-sig',newline='') as stream:
        rows=list(csv.DictReader(stream))
    grouped={}
    for row in rows:
        for key in ('episodes','windows'):
            row[key]=int(row[key])
        for key in ('endpoint_force_mae_N','interval_peak_mae_N','height_mae_m',
                    'fixed_calibration_joint_coverage','calibration_peak_radius_N'):
            row[key]=float(row[key])
        identity=policy_identity(row['controller'])
        if identity:
            grouped.setdefault((identity['method'],row['domain']),[]).append(row)
    result=[]
    for (method,domain),records in sorted(grouped.items()):
        values={}
        for key in ('endpoint_force_mae_N','interval_peak_mae_N','height_mae_m','fixed_calibration_joint_coverage'):
            samples=np.array([r[key] for r in records])
            values[key]={'mean':samples.mean(),'training_seed_sd':samples.std(ddof=1) if len(samples)>1 else None}
        result.append({'method':method,'domain':domain,'fixed_policy_runs':len(records),
                       'episodes_per_policy':[r['episodes'] for r in records],
                       'per_policy_coverage':[r['fixed_calibration_joint_coverage'] for r in records],**values})
    return {'rows':rows,'grouped':result,'provenance':provenance,
            'scope':'retrospective forecasts conditioned on actually executed future actions; original calibration unchanged'}


