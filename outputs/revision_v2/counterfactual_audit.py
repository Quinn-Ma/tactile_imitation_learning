"""Prospective alternate-action diagnostic in executed MuJoCo branches.

Every branch independently resets and replays exactly the same stored action
prefix. Three observations warm each frozen model; then all nine five-step
action sequences are forecast without updating history. Outcomes are measured
by the simulator, never generated by the learned model. Diagnostic outcomes
must not select checkpoints, controller gains, or primary evaluation seeds.

This probes local action effects around one prefix policy. Five-step selection
regret is a local diagnostic, not long-horizon lifting or closed-loop safety.
"""
from __future__ import annotations

