def main():
    parser=argparse.ArgumentParser()
    base=Path(__file__).resolve().parent
    parser.add_argument('--world-runs',default=str(base/'runs'))
    # One evaluation cohort per analysis. Supplying the wider simulation tree
    # is rejected once it contains both original and exploratory cohorts.
    parser.add_argument('--controls',default=str(base.parent/'simulation'/'evaluation_main'))
    parser.add_argument('--executed-forecasts',default=str(base/'executed_forecasts'))
    parser.add_argument('--output',default=str(base/'analysis'))
    parser.add_argument('--bootstrap',type=int,default=2000)
    parser.add_argument('--seed',type=int,default=90210)
    parser.add_argument('--primary-takeover',type=int,default=44)
    parser.add_argument('--no-plots',action='store_true')
    parser.add_argument('--dry-run',action='store_true')
    args=parser.parse_args()
    warnings=[];rng=np.random.default_rng(args.seed)
    world=world_results(args.world_runs,args.bootstrap,rng,warnings)
    controls=controls_results(args.controls,args.bootstrap,rng,args.primary_takeover,warnings)
    executed=executed_forecast_results(args.executed_forecasts,warnings)
    if args.dry_run:
        print(json.dumps({'world_completed_runs':world['completed_runs'],'control_completed_runs':controls['completed_runs'],
                          'warnings':warnings},ensure_ascii=False));return
    output=Path(args.output);output.mkdir(parents=True,exist_ok=True)
    save_json(output/'world_model_analysis.json',world)
    save_json(output/'control_analysis.json',controls)
    save_json(output/'executed_forecast_analysis.json',executed)
    save_json(output/'analysis_metadata.json',{'arguments':vars(args),'warnings':warnings,
         'missing_data_policy':'Never impute absent experiments or metrics; exclude unverified pairing.'})
    write_csv(output/'world_model_run_metrics.csv',world['individual'])
    write_csv(output/'world_model_paired_modality.csv',world['paired_modality_differences'])
    write_csv(output/'world_model_calibration.csv',world['calibration'])
    write_csv(output/'controller_metrics.csv',controls['statistics'])
    write_csv(output/'controller_paired_differences.csv',controls['paired'])
    write_csv(output/'controller_method_metrics.csv',controls['grouped_methods'])
    write_csv(output/'controller_method_paired_differences.csv',controls['grouped_paired'])
    files=[] if args.no_plots else plot_results(world,controls,output)
    for generated_name in ('forecast_horizons.png','modality_comparison.png','forecast_ablations.png',
                           'control_outcomes.png','control_force_phases.png','control_methods.png','reward_alignment_id.png'):
        stale=output/generated_name
        if generated_name not in files and stale.exists():
            stale.unlink()  # only this script's known generated images in its output directory
    report(world,controls,executed,files,warnings,output)
    print(json.dumps({'world_completed_runs':world['completed_runs'],'control_completed_runs':controls['completed_runs'],
                      'plots':files,'report':str((output/'report_zh.md').resolve()),'warnings':warnings},ensure_ascii=False))


if __name__=='__main__':
    main()
